<script>
    document.addEventListener('DOMContentLoaded', function () {
        const tabs = document.querySelectorAll('.story-tab');
        const slides = document.querySelectorAll('.testimonial-slide');

        if (tabs.length && slides.length) {
            tabs.forEach((tab, index) => {
                tab.addEventListener('click', function () {
                    // Remove active from all tabs
                    tabs.forEach(t => {
                        t.classList.remove('active', 'border-blue-600', 'text-blue-800', 'shadow-md');
                        t.classList.add('border-gray-200', 'text-gray-600');
                    });

                    // Set active to current tab
                    this.classList.add('active', 'border-blue-600', 'text-blue-800', 'shadow-md');
                    this.classList.remove('border-gray-200', 'text-gray-600');

                    // Hide all slides
                    slides.forEach(s => s.classList.add('hidden'));

                    // Show selected slide
                    if (slides[index]) {
                        slides[index].classList.remove('hidden');
                    }
                });
            });
        }
    });
</script>
